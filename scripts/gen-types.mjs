// Regenerates src/types/database.ts from the live Supabase schema.
//
//   npm run gen:types
//
// Requires a one-time `npx supabase login` on this machine. The project ref is
// not a secret (it is the subdomain of the public project URL); override it with
// SUPABASE_PROJECT_REF to point at a different project.
//
// Guard: refuses to overwrite the file if the generated schema is missing any
// table in EXPECTED_TABLES. Generating before the migration is applied returns
// an empty `Database` type, which would otherwise be committed silently.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const PROJECT_REF = process.env.SUPABASE_PROJECT_REF ?? 'bsjodruzecdaymnxjade'
const SUPABASE_CLI = 'supabase@2.119.0'
const OUT = 'src/types/database.ts'
const EXPECTED_TABLES = ['players', 'games', 'scouting_events']

const generated = execFileSync(
  'npx',
  ['--yes', SUPABASE_CLI, 'gen', 'types', 'typescript', '--project-id', PROJECT_REF, '--schema', 'public'],
  { encoding: 'utf8', shell: process.platform === 'win32', stdio: ['ignore', 'pipe', 'inherit'] },
)

const lines = generated.split(/\r?\n/)
const missing = EXPECTED_TABLES.filter((t) => !lines.includes(`      ${t}: {`))
if (missing.length > 0) {
  console.error(
    `gen:types aborted — generated schema is missing: ${missing.join(', ')}.\n` +
      `Apply the migrations to project ${PROJECT_REF} first, then re-run. ${OUT} was not changed.`,
  )
  process.exit(1)
}

const header =
  '// GENERATED by `npm run gen:types` from Supabase project ' + PROJECT_REF + ' (schema: public).\n' +
  '// Do not edit by hand — change SQL in supabase/migrations/, apply it, then regenerate.\n' +
  '// See docs/typegen-notes.md.\n\n'

writeFileSync(OUT, header + generated)
console.log(`Wrote ${OUT} (tables: ${EXPECTED_TABLES.join(', ')})`)
